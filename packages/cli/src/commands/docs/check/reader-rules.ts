import { dirname, extname, join, resolve } from 'node:path';

import {
  isIndexOnlyLeaf,
  parseIndexContents,
  resolveEntryTarget,
} from '@commands/docs/nav/contents';
import { isExcludedPath } from '@commands/docs/shared/exclusions';
import { DOCS_CHECK_THRESHOLDS } from '@config/documentation-check';

import type { Report } from './check.types';
import {
  containedFile,
  inside,
  posix,
  present,
  readerDirectories,
  type CheckTarget,
} from './files';
import { nodeText, type ParsedPage } from './markdown';

export async function checkReaders(
  target: CheckTarget,
  pages: ParsedPage[],
  report: Report,
): Promise<void> {
  const t = {
    ...DOCS_CHECK_THRESHOLDS,
    ...target.documentation.check?.thresholds,
  };
  const byPath = new Map(pages.map((p) => [p.path, p]));
  const pagePaths = pages.map((p) => p.path);
  const dirs = readerDirectories(pagePaths);
  const separators = new Map<string, { path: string; line: number }>();
  for (const dir of dirs) {
    const path = posix(join(dir, 'index.md'));
    const page = byPath.get(path);
    const indexOnlyLeaf = isIndexOnlyLeaf(dir, pagePaths);
    let grouped = false;
    if (!page)
      report(
        'directory-index',
        'error',
        path,
        'Reader-bearing directory needs index.md with a nonempty ## Contents map.',
      );
    else {
      try {
        const entries = parseIndexContents(page.body, path, {
          locations: true,
        });
        const retained = [];
        for (const entry of entries) {
          const lexical = resolve(
            target.contentRoot,
            dir,
            entry.href.split('#')[0] ?? '',
          );
          if (
            inside(target.contentRoot, lexical) &&
            isExcludedPath(
              target.matcher,
              posix(lexical.slice(target.contentRoot.length + 1)),
            )
          )
            continue;
          retained.push(entry);
          if (entry.description && /(?:\.\.\.|…)\s*$/.test(entry.description))
            report(
              'contents-description',
              'error',
              path,
              'Contents description is truncated; finish the sentence.',
              entry.line,
            );
          if (entry.separator)
            separators.set(entry.separator, { path, line: entry.line! });
          try {
            // Existing strict Contents resolution owns local map semantics.
            // Leaf same-page anchors resolve without error; the links rule
            // below reports any that name a missing heading.
            await resolveEntryTarget(
              target.contentRoot,
              join(target.contentRoot, dir),
              dir,
              entry,
              ['.md', '.mdx'],
              target.matcher,
              { indexOnlyLeaf },
            );
          } catch (error) {
            report(
              'directory-index',
              'error',
              path,
              String((error as Error).message),
              entry.line,
            );
          }
        }
        grouped = retained.some((e) => e.group !== undefined);
        if (dir === '.' && !grouped) {
          if (retained.length > t.rootError)
            report(
              'root-width',
              'error',
              path,
              `Flat root has ${retained.length} Contents links; maximum ${t.rootError}.`,
            );
          else if (retained.length > t.rootWarn)
            report(
              'root-width',
              'warn',
              path,
              `Flat root has ${retained.length} Contents links; group above ${t.rootWarn}.`,
            );
        }
        const catalog =
          page.frontmatter.catalog === true ||
          page.source.includes(
            '<!-- AUTOGENERATED by `oat docs generate-index`.',
          );
        if (!grouped && !catalog) {
          if (retained.length > t.contentsError)
            report(
              'contents-width',
              'error',
              path,
              `Ungrouped Contents has ${retained.length} links; maximum ${t.contentsError}.`,
            );
          else if (retained.length > t.contentsWarn)
            report(
              'contents-width',
              'warn',
              path,
              `Ungrouped Contents has ${retained.length} links; group above ${t.contentsWarn}.`,
            );
        }
        const contentsHeading = page.nodes.find(
          (n) =>
            n.type === 'heading' &&
            n.depth === 2 &&
            nodeText(n).trim() === 'Contents',
        );
        const words = page.nodes
          .filter(
            (n) =>
              n.type === 'paragraph' &&
              (n.position?.end.line ?? Infinity) <
                (contentsHeading?.position?.start.line ?? 0),
          )
          .map(nodeText)
          .join(' ')
          .trim()
          .split(/\s+/)
          .filter(Boolean).length;
        if (words < t.overviewWords)
          report(
            'overview',
            'warn',
            path,
            `Overview has ${words} words; use at least ${t.overviewWords} before Contents.`,
          );
      } catch (error) {
        report('directory-index', 'error', path, (error as Error).message);
      }
    }
    const count = pages.filter((p) => dirname(p.path) === dir).length;
    const child = dirs.some(
      (d) => d !== dir && (dir === '.' || d.startsWith(`${dir}/`)),
    );
    // A single-page section renders fine, so its shape is a style suggestion.
    if (indexOnlyLeaf)
      report(
        'leaf-size',
        'warn',
        path,
        'Index-only leaf; consider flattening it to a single page or adding reader pages.',
      );
    else if (!child && count === 2)
      report(
        'leaf-size',
        'warn',
        path,
        'Leaf has only two direct reader pages including index.md; consider flattening.',
      );
    if (!grouped) {
      if (count > t.folderError)
        report(
          'folder-size',
          'error',
          path,
          `Folder has ${count} direct reader pages including index; maximum ${t.folderError} without groups.`,
        );
      else if (count > t.folderWarn)
        report(
          'folder-size',
          'warn',
          path,
          `Folder has ${count} direct reader pages including index; group above ${t.folderWarn}.`,
        );
    }
    const depth = dir === '.' ? 0 : dir.split('/').length;
    if (depth >= t.depthError)
      report(
        'depth',
        'error',
        path,
        `Directory depth ${depth}; error at ${t.depthError} (content root is 0).`,
      );
    else if (depth >= t.depthWarn)
      report(
        'depth',
        'warn',
        path,
        `Directory depth ${depth}; warning at ${t.depthWarn} (content root is 0).`,
      );
  }
  if (separators.size > 1)
    for (const { path, line } of separators.values())
      report(
        'contents-separator',
        'warn',
        path,
        `Contents separators differ within this tree (${[...separators.keys()].sort().join(', ')}).`,
        line,
      );
  for (const p of pages) {
    if (!p.frontmatterError) {
      const desc = p.frontmatter.description;
      if (typeof desc !== 'string' || !desc.trim())
        report(
          'description',
          'error',
          p.path,
          'Frontmatter description is required and must be nonempty.',
          1,
        );
      else if (
        desc.trim().length < t.descriptionMin ||
        desc.trim().length > t.descriptionMax
      )
        report(
          'description',
          'warn',
          p.path,
          `Description has ${desc.trim().length} characters; expected ${t.descriptionMin}–${t.descriptionMax}.`,
          1,
        );
    }
    const h1 = p.nodes.filter((n) => n.type === 'heading' && n.depth === 1);
    if (h1.length !== 1)
      report(
        'h1',
        'error',
        p.path,
        `Expected one real H1; found ${h1.length}.`,
        h1[1]?.position?.start.line ?? 1,
      );
    const reference =
      p.frontmatter.type === 'reference' ||
      /(?:^|\/)references?(?:\/|$)/.test(p.path);
    const lines =
      p.source.split(/\r?\n/).length - (p.source.endsWith('\n') ? 1 : 0);
    const limit = reference ? t.referenceLines : t.pageLines;
    if (lines > limit)
      report(
        'page-length',
        'warn',
        p.path,
        `Page has ${lines} physical source lines; limit ${limit}${reference ? ' for reference pages' : ''}.`,
        // The first physical line past the limit.
        limit + 1,
      );
    const h3Nodes = p.nodes.filter(
      (n) => n.type === 'heading' && n.depth === 3,
    );
    const h3 = h3Nodes.length;
    if (reference && h3 > t.referenceH3)
      report(
        'page-length',
        'warn',
        p.path,
        `Reference page has ${h3} real H3 headings; limit ${t.referenceH3}.`,
        // The first H3 past the limit.
        h3Nodes[t.referenceH3]?.position?.start.line ?? 1,
      );
    for (const link of p.links) {
      const href = link.href;
      if (/^(?:[a-z][a-z\d+.-]*:|\/\/)/i.test(href)) continue;
      let pathname: string;
      let anchor: string;
      try {
        const hash = href.indexOf('#');
        pathname = decodeURIComponent(
          (hash < 0 ? href : href.slice(0, hash)).split('?')[0]!,
        );
        anchor = hash < 0 ? '' : decodeURIComponent(href.slice(hash + 1));
      } catch {
        report(
          'links',
          'error',
          p.path,
          `Malformed percent encoding in link "${href}".`,
          link.line,
        );
        continue;
      }
      if (!pathname) {
        if (anchor && !p.anchors.has(anchor))
          report(
            'links',
            'error',
            p.path,
            `Unresolved anchor "${href}".`,
            link.line,
          );
        continue;
      }
      if (pathname.startsWith('~/')) continue; // provenance reports it, never read home paths
      const file = pathname.startsWith('/')
        ? resolve(target.contentRoot, `.${pathname}`)
        : resolve(target.contentRoot, dirname(p.path), pathname);
      if (!inside(target.contentRoot, file)) continue; // provenance warns without outside IO
      const relativePath = posix(file.slice(target.contentRoot.length + 1));
      if (isExcludedPath(target.matcher, relativePath)) continue;
      let resolved = file;
      let isFile = await containedFile(target.contentRoot, file);
      if (!isFile && !extname(pathname)) {
        for (const suffix of ['.md', '.mdx', '/index.md'])
          if (await containedFile(target.contentRoot, file + suffix)) {
            resolved = file + suffix;
            isFile = true;
            break;
          }
      }
      // Framework public assets have a separate explicit allowed root. Rendered
      // absolute routes are validated only when they identify a reader file.
      if (!isFile && pathname.startsWith('/') && link.image) {
        const publicRoot = join(target.appRoot, 'public');
        isFile =
          (await present(publicRoot)) &&
          (await containedFile(
            publicRoot,
            resolve(publicRoot, `.${pathname}`),
          ));
      }
      if (
        !isFile &&
        pathname.startsWith('/') &&
        !link.image &&
        !/\.mdx?$/.test(pathname)
      )
        continue;
      if (!isFile)
        report(
          'links',
          'error',
          p.path,
          `Unresolved in-root link "${href}".`,
          link.line,
        );
      else if (anchor && /\.mdx?$/.test(resolved)) {
        const destination = byPath.get(
          posix(resolved.slice(target.contentRoot.length + 1)),
        );
        if (destination && !destination.anchors.has(anchor))
          report(
            'links',
            'error',
            p.path,
            `Unresolved anchor "${href}".`,
            link.line,
          );
      }
    }
  }
}

export function checkProvenance(
  target: CheckTarget,
  pages: ParsedPage[],
  report: Report,
): void {
  const patterns = [
    /\.oat\//u,
    /\b[Bb][Ll]-[\w-]+/u,
    /(?:~\/|\/Users\/|\/home\/)/u,
    ...(target.documentation.check?.provenance?.ticketPatterns ?? []).map(
      (p) => new RegExp(p, 'u'),
    ),
    ...(target.documentation.check?.provenance?.milestonePatterns ?? []).map(
      (p) => new RegExp(p, 'u'),
    ),
  ];
  for (const p of pages) {
    p.source.split(/\r?\n/).forEach((text, line) => {
      if (patterns.some((pattern) => pattern.test(text)))
        report(
          'provenance',
          'warn',
          p.path,
          'Reader page contains a planning/backlog/home path or configured ticket/milestone pattern; remove it or record a reason-bearing decision-pointer exception.',
          line + 1,
        );
    });
    for (const link of p.links) {
      if (/^(?:[a-z][a-z\d+.-]*:|\/)/i.test(link.href)) continue;
      const href = link.href.split(/[?#]/)[0]!;
      let decoded: string;
      try {
        decoded = decodeURIComponent(href);
      } catch {
        continue;
      }
      if (
        !inside(
          target.contentRoot,
          resolve(target.contentRoot, dirname(p.path), decoded),
        )
      )
        report(
          'provenance',
          'warn',
          p.path,
          `Link "${link.href}" escapes the docs root; target was not read.`,
          link.line,
        );
    }
  }
}
